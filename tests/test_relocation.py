"""Упоминание переезда в тексте вакансии.

Дыра, которую это закрывает, измерена 2026-08-26: региональный штраф
считается по полю `addressLocality` из разметки страницы, а требование
переехать живёт в ТЕКСТЕ описания. Вакансия с московским `area` и
переездом в Елабугу в теле описания проходит мимо штрафа целиком.

Отбор здесь детерминированный и без сети — по той же причине, по которой
он не отдан модели: замер показал, что llama3 находит пять упоминаний из
одиннадцати, а слова находят все одиннадцать. Модели остаётся то, в чём
она измеренно сильна, — назвать город.
"""

import pytest

from hh_search.filtering.relocation import mentions_relocation

# Живые фрагменты из базы на 2026-08-26 — не выдуманные примеры. Каждый
# был найден замером, и на каждом стоит своё решение.
REAL_RELOCATION = [
    "Работа в Елабуге, компания помогает с переездом и арендой жилья",
    "релокационный пакет. Оплатим дорогу и первый месяц аренды квартиры в Москве",
    "Официальное трудоустройство по ТК Уз с первого дня; Конкурентная зарплата, "
    "релокационный пакет",
    "Возможность релокации на Кипр",
    "Формат работы: удалённый (возможна релокация в Анталью по желанию)",
]

# Тот же корень, но переезжают не люди. Из-за них голый поиск слова давал
# ложные срабатывания — два из одиннадцати на замере.
NOT_PEOPLE = [
    "Переезд приложений с legacy-инфраструктуры в Kubernetes",
    "Опыт миграции систем с поэтапным переездом (без «большого взрыва»)",
    "проекты, в которых уже есть микросервисная архитектура, либо идёт переезд на неё",
    "Переезд данных из Oracle в PostgreSQL",
]


@pytest.mark.parametrize("text", REAL_RELOCATION)
def test_a_human_relocation_is_found(text: str) -> None:
    assert mentions_relocation(text)


@pytest.mark.parametrize("text", NOT_PEOPLE)
def test_a_technical_migration_is_not_a_relocation(text: str) -> None:
    """«Переезд приложений» — не переезд человека.

    Молча посчитать его переездом значило бы вывесить владельцу пометку
    «переезд» над обычной удалённой вакансией DevOps — и обесценить
    пометку на всех остальных.
    """
    assert not mentions_relocation(text)


def test_a_description_without_the_topic_is_not_flagged() -> None:
    assert not mentions_relocation("Ищем ведущего разработчика C++ для встраиваемых систем")


def test_both_senses_in_one_text_still_count_as_relocation() -> None:
    """Есть хоть одно человеческое упоминание — пометка ставится.

    Живой случай с замера: у DevOps-вакансии переезжают и приложения, и
    сам сотрудник. Снять пометку из-за технического упоминания значило бы
    потерять настоящее — а цена ошибки здесь асимметрична, как и везде в
    этом проекте: лишняя пометка стоит взгляда, пропущенная — переезда.
    """
    text = "Переезд приложений в Kubernetes. Компания оплачивает переезд сотрудника в Казань."

    assert mentions_relocation(text)


def test_the_word_is_matched_by_its_stem_and_not_by_its_form() -> None:
    """«Релокация», «релокационный», «релоцируем» — одно и то же слово."""
    for form in ("релокация", "релокационный пакет", "relocation package", "переехать в Пермь"):
        assert mentions_relocation(f"Условия: {form}"), form
