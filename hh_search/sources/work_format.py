"""Формат работы со страницы вакансии — вынесен из `vacancy_page.py`.

Перенос по той же причине, что увёл сюда `salary.py`: `vacancy_page.py`
стоял вплотную к ориентиру §4.3 (≤150 строк кода), и добавление разбора
формата туда же перевело бы файл за границу без законной причины — не
переплетения инвариантов (как у `storage/repository.py` из таблицы
исключений), а просто ещё одного самостоятельного извлечения, как и
зарплата.

Источник — встроенное состояние страницы, а не блок `data-qa=
"work-formats-text"`: тот отдаёт локализованный текст («Формат работы:
удалённо»), который сменится от смены языка интерфейса, а перечисление
`workFormatsElement` — стабильный идентификатор hh.ru. Значения приходят
HTML-экранированными (`&#34;` вместо `"`), потому что весь блок вставлен
как значение HTML-атрибута, поэтому разбору предшествует `unescape`.
"""

import logging
import re
from dataclasses import dataclass
from html import unescape

from hh_search.domain.models import WorkFormat

logger = logging.getLogger(__name__)

# Встроенное состояние — единственный `<template id="HH-Lux-InitialState">`
# страницы. Поиск ограничен его содержимым по той же причине, по которой
# `_canonical_targets` в `sources/listing.py` ограничен содержимым `<head>`:
# первое совпадение где угодно в документе означало, что подделка в области,
# которой управляет ЧУЖОЙ, побеждает настоящий ключ. Здесь чужой —
# работодатель: на живой фикстуре отрендеренное описание вакансии стоит на
# смещении ~74 000, а состояние начинается только на ~186 000, поэтому
# строка `"workFormatsElement":["REMOTE"]`, вписанная в текст описания,
# опережала настоящий ключ и делала московскую офисную вакансию удалённой —
# штраф −40 снимался, отчёт печатал «удалённо», оценка 60.0 превращалась в
# 100.0. Сторож `WorkFormatBlockStats` на это молчал по построению: формат
# ведь нашёлся.
_STATE_RE = re.compile(r'<template[^>]+id="HH-Lux-InitialState"[^>]*>(.*?)</template>', re.S)
# Ключ `workFormatsElement` вместе с ОБЁРТКОЙ `"workFormats":[{…}]`, а не
# сам по себе и не более широкий `workFormats`: страница несёт под именем
# `workFormats` ещё два посторонних блока — краткую копию вида
# `"workFormats":["ON_SITE"]` в блоке похожих вакансий и СЛОВАРЬ всех
# значений перечисления для отрисовки фильтра
# (`"workFormats":[{"id":"ON_SITE","text":"..."},{"id":"REMOTE",...}]`).
# Второй — ловушка: в нём перечислены ВСЕ форматы разом, и совпадение по
# широкому ключу приписало бы любой вакансии полный набор форматов
# независимо от того, что у неё на самом деле указано. Обёртка отсеивает
# оба: у краткой копии после `[` идёт строка, а не `{`, у словаря внутри
# `{` идёт `"id"`, а не `"workFormatsElement"`.
_WORK_FORMATS_RE = re.compile(r'"workFormats":\[\{"workFormatsElement":\[([^\]]*)\]')
_TOKEN_RE = re.compile(r'"([A-Z_]+)"')


def extract_work_formats(html: str) -> frozenset[WorkFormat]:
    """Форматы работы вакансии. Пустое множество — блока нет или он спорен.

    Берутся ВСЕ вхождения ключа во встроенном состоянии, а не первое, и от
    них требуется согласие: на живой странице вхождение ровно одно
    (проверено на обеих фикстурах), поэтому второе, не совпавшее с первым,
    означает не вторую истину, а чужой текст, попавший в состояние (описание
    вакансии лежит там же и пишется работодателем). При расхождении
    возвращается пустое множество — ровно то же, что при отсутствии блока:
    неизвестный формат штрафа не несёт, и отказ в пользу неведения дешевле
    выбора наугад между двумя источниками, один из которых подделан.

    Неизвестное значение перечисления (hh.ru заведёт новое — либо страница
    отдаст его раньше, чем мы узнаем про него) отбрасывается по одному, а
    не роняет разбор остальных: список — это `frozenset`, а не одно
    значение, и потеря соседних форматов из-за одного незнакомого была бы
    отдельной, никем не заказанной потерей.
    """
    state = _STATE_RE.search(unescape(html))
    if state is None:
        return frozenset()
    # Согласие сверяется по МНОЖЕСТВУ токенов, а не по тексту совпадения:
    # порядок значений внутри списка ничего не означает, и разошедшийся
    # только им блок расхождением не является.
    variants = {
        frozenset(_TOKEN_RE.findall(raw)) for raw in _WORK_FORMATS_RE.findall(state.group(1))
    }
    if len(variants) != 1:
        return frozenset()
    formats: set[WorkFormat] = set()
    for token in next(iter(variants)):
        try:
            formats.add(WorkFormat(token))
        except ValueError:
            continue
    return frozenset(formats)


@dataclass
class WorkFormatBlockStats:
    """Счётчик страниц без формата работы — сторож дрейфа `workFormatsElement`.

    По образцу `SalaryBlockStats` из `vacancy_page.py`: по одной странице
    сказать нельзя ничего (формат мог быть не заполнен работодателем), а
    прогон, где он не нашёлся НИ РАЗУ, почти наверняка означает не рынок
    без форматов, а переименованный ключ встроенного состояния. Разница
    видна только в агрегате.
    """

    pages: int = 0
    without_formats: int = 0

    def record(self, formats: frozenset[WorkFormat]) -> None:
        self.pages += 1
        if not formats:
            self.without_formats += 1

    def log_summary(self) -> None:
        if not self.pages:
            return
        if self.without_formats == self.pages:
            logger.warning(
                "ни с одной из %d страниц вакансий не удалось прочитать формат работы "
                '(ключ "workFormatsElement" встроенного состояния). Либо ни у одной '
                "вакансии он не указан, либо ключ переименован (или состояние "
                "перестроено) и формат потерян для всех",
                self.pages,
            )
        elif self.without_formats:
            logger.info(
                "формат работы не указан у %d из %d страниц вакансий",
                self.without_formats,
                self.pages,
            )
