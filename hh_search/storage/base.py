"""Точка расширения `Repository` из спеки §4.2 и коды, общие для слоёв.

Протокол объявлен здесь, а не в `repository.py`, ровно по той же причине,
по которой `Scorer` и `Sink` живут в своих `base.py`: конвейер обязан
зависеть от интерфейса, а не от реализации. До этого модуля обещание
§4.2 «`PostgresRepository` не потребует правок в pipeline» было
неисполнимым по типам — четыре модуля конвейера были аннотированы
конкретным `SqliteRepository`, и `mypy --strict`, часть ворот проекта,
отвергал любую альтернативную реализацию, сколько бы безупречно та ни
работала в рантайме. Проверено исполнением: `tests/test_pipeline.py`
подставляет в `run_once` реализацию, хранящую всё в памяти, и она
проходит и прогон, и `mypy --strict`.

**§4.2 называет `Repository` «протоколом на два-три метода», и это
неверно.** Фактический набор — двадцать методов: три непересекающиеся
выборки со своими записями, возврат из отказа префильтра, журнал
прогонов и кэш условных запросов. Ужать его нечем: каждый метод
вызывается конвейером, и ни один не выводится из остальных. Число
названо здесь честно, чтобы следующий читатель спеки не искал
несуществующей простоты.

Коды статусов и причин отказа тоже здесь: конвейер обязан их называть
(`mark_rejected(..., REJECT_CODE_PREFILTER)`), а импортировать ради
константы модуль, в котором живёт SQL, — значит держать зависимость от
реализации в том самом файле, который её не должен знать.
"""

from collections.abc import Sequence
from datetime import datetime
from typing import Protocol

from hh_search.domain.models import (
    DiscoveredVacancy,
    ScoreBreakdown,
    ScoredVacancy,
    VacancyDetails,
    VacancyFacts,
)

STATUS_NEW = "new"
STATUS_REJECTED = "rejected"
STATUS_REPORTED = "reported"

# Машинные коды причины отказа — колонка `reject_code`, отдельная от
# человекочитаемого `reject_reason`. Разведены они не ради красоты:
# отказ префильтра обратим (решение о нём локальное, и правка конфига
# обязана его отменять), а исчерпание попыток скачивания — нет. Выбирать
# обратимые строки разбором текста причины нельзя: текст префильтра
# перечисляет совпавшие стоп-слова и будет меняться, а разъехавшийся
# префикс молча изменил бы множество возвращаемых вакансий — ровно тот
# класс тихого отказа, против которого написан весь слой хранилища.
REJECT_CODE_PREFILTER = "prefilter"
REJECT_CODE_ENRICH_FAILED = "enrich_failed"

# Текст причины при исчерпании попыток скачивания (спека §5.2). Ставится
# внутри `bump_enrich_attempt`, тем же UPDATE, что и счётчик, и совпадает
# с кодом: этому отказу нечего добавить к коду, тогда как причина
# префильтра перечисляет слова и потому от кода отличается.
REJECT_ENRICH_FAILED = REJECT_CODE_ENRICH_FAILED

# Потолок строк, поднимаемых В ПАМЯТЬ одной выборкой, если вызывающий не
# назвал своего. Не «оптимизация»: без него `unreported()` на базе с
# 50 000 готовых вакансий строил 50 000 pydantic-моделей с описаниями —
# замер 12.5 с и 762 МБ RSS, то есть OOM на VPS с гигабайтом ровно в том
# сценарии, где отказ уже случился (приёмники не приняли отчёт, очередь
# копится). Умолчание выбрано так, чтобы НИ ОДИН вызов — включая тесты и
# будущий код, забывший про лимит, — не мог оказаться неограниченным.
# Конвейер передаёт сюда `app.limits.rows_per_batch`, и это же число
# служит здесь умолчанием (см. `config/models.py`).
DEFAULT_BATCH_LIMIT = 500


class Repository(Protocol):
    """Хранилище в том объёме, в каком его знает конвейер (спека §4.2).

    Три выборки со `status = 'new'` не пересекаются и вместе покрывают
    все состояния: `pending_enrichment` (описания нет — надо в сеть),
    `pending_scoring` (описание есть, оценки нет — надо пересчитать
    локально) и `unreported` (заполнено оба — готово к отправке).
    Реализация обязана сохранять это разбиение: на нём держится инвариант
    «страница вакансии скачивается не более одного раза за жизнь».

    Все выборки, поднимающие строки в память, принимают `limit`. Это
    часть контракта, а не деталь реализации: объём работы одного прогона
    обязан быть ограничен сверху, иначе бэклог превращает прогон в OOM.
    """

    # --- discovery -----------------------------------------------------

    def add_discovered(self, vacancy: DiscoveredVacancy, cluster: str, weight: int) -> bool:
        """Записать найденную вакансию. `True` — она новая для базы."""
        ...

    def cache_headers(self, url: str) -> dict[str, str]:
        """Валидаторы условного запроса для этого URL."""
        ...

    def save_cache_headers(self, url: str, etag: str | None, last_modified: str | None) -> None:
        """Запомнить валидаторы — только ПОСЛЕ того, как страница разобрана."""
        ...

    def reset_cache(self, url: str) -> None:
        """Забыть валидаторы: иначе 304 спрячет дрейф формата за нулевой работой."""
        ...

    # --- префильтр: сеть не задействуется --------------------------------

    def pending_titles(self, max_attempts: int) -> list[tuple[str, str]]:
        """`(id, заголовок)` всей очереди обогащения — всё, чем живёт отсев."""
        ...

    def mark_rejected(self, vacancy_id: str, reason: str, code: str) -> None:
        """Отказ: человекочитаемая причина и машинный код — одним UPDATE."""
        ...

    def rejected_by_prefilter(self) -> list[tuple[str, str]]:
        """`(id, заголовок)` строк, отбракованных ПРЕФИЛЬТРОМ, — для возврата."""
        ...

    def requeue_prefiltered(self, ids: Sequence[str]) -> int:
        """Вернуть их в очередь. Одна транзакция, идемпотентно."""
        ...

    # --- 1: обогащение, единственная выборка, ходящая в сеть -------------

    def pending_enrichment(self, max_attempts: int, limit: int) -> list[DiscoveredVacancy]:
        """Очередь обогащения. `limit` — прямой потолок запросов к hh.ru за прогон."""
        ...

    def bump_enrich_attempt(self, vacancy_id: str, max_attempts: int) -> int:
        """Инкремент попытки и, при исчерпании лимита, отказ — ОДНИМ UPDATE."""
        ...

    def save_description(self, vacancy_id: str, details: VacancyDetails) -> None:
        """Сохранить страницу без оценки: она скачана, оценки ещё нет."""
        ...

    def save_enriched(
        self, vacancy_id: str, details: VacancyDetails, score: ScoreBreakdown
    ) -> None:
        """Вся страница и оценка одним UPDATE — обычный путь после скачивания."""
        ...

    def stalled_by_attempts(self, max_attempts: int) -> int:
        """Сколько строк выведено из очереди обогащения снижением лимита попыток."""
        ...

    def stalled_rows_hint(self, max_attempts: int) -> str:
        """Чем человек найдёт эти строки в ЭТОМ хранилище.

        Запрос принадлежит слою, который его исполнит: написанный в тексте
        лога конвейера, он протухнет при первой правке схемы и будет
        врать, если хранилище сменится (§4.3 — про SQL знает только
        `storage/`).
        """
        ...

    # --- 2: пересчёт оценки, сеть не задействуется -----------------------

    def pending_scoring(self, limit: int) -> list[tuple[DiscoveredVacancy, VacancyDetails]]:
        """Описание есть, оценки нет: пересчитать локально."""
        ...

    def count_pending_scoring(self) -> int:
        """Сколько их всего. COUNT(*), а не длина выборки: счётчик `stuck`
        обязан оставаться верным при любом `limit` и не декодировать строк."""
        ...

    def save_score(self, vacancy_id: str, score: ScoreBreakdown) -> None:
        """Записать пересчитанную оценку, не трогая описание."""
        ...

    # --- 2.5: вектор описания --------------------------------------------

    def pending_embedding(self, model: str, limit: int) -> list[tuple[str, str]]:
        """Описание есть, вектора ЭТОЙ модели нет: (id, текст под эмбеддинг).

        Имя модели в предикате, а не проверка на NULL: правка
        `llm.embed_model` обязана ставить корпус в очередь заново сама.
        """
        ...

    def save_embedding(self, vacancy_id: str, model: str, vector: bytes) -> None:
        """Вектор и имя отдавшей его модели — одним UPDATE, не двумя."""
        ...

    def embeddings(self, ids: Sequence[str], model: str) -> dict[str, bytes]:
        """Сырые BLOB'ы названных вакансий, только этой модели.

        Именно сырые: формат упаковки принадлежит `llm/semantic.py`, и
        зависимости `storage → llm` в этом проекте нет.
        """
        ...

    # --- 2.6: факты описания ---------------------------------------------

    def pending_facts(self, model: str, limit: int) -> list[tuple[str, str, str]]:
        """Описание есть, фактов ЭТОЙ модели нет: (id, заголовок, описание)."""
        ...

    def save_facts(self, vacancy_id: str, model: str, facts: VacancyFacts) -> None:
        """Факты и имя извлёкшей их модели — одним UPDATE, не двумя."""
        ...

    def facts(self, ids: Sequence[str], model: str) -> dict[str, VacancyFacts]:
        """Факты названных вакансий, только этой модели. Нечитаемые пропускаются."""
        ...

    # --- 3: отчёт --------------------------------------------------------

    def unreported(self, limit: int) -> list[ScoredVacancy]:
        """Готовое к отправке, самое высоко оценённое — первым."""
        ...

    def mark_reported(self, ids: Sequence[str]) -> None:
        """Пометить отправленным. Вызывается только после успеха ВСЕХ приёмников."""
        ...

    # --- журнал прогонов -------------------------------------------------

    def start_run(self) -> int:
        """Открыть строку журнала. Возвращает её id."""
        ...

    def finish_run(
        self,
        run_id: int,
        status: str,
        *,
        finished_at: datetime | None = None,
        **counters: int | str | None,
    ) -> None:
        """Закрыть строку журнала — на ЛЮБОМ исходе прогона."""
        ...

    def corrupted_count(self) -> int:
        """Сколько строк ушло в терминальный карантин за жизнь этого объекта."""
        ...


class Housekeeper(Protocol):
    """Хранилище в том объёме, в каком его знает УБОРКА (спека 2026-08-01 §3).

    Протокол отдельный, а не пять методов, дописанных в `Repository`, по
    двум причинам. Уборка не участвует в прогоне: `run_once` не зовёт ни
    одного из этих методов, и класть их в протокол, чей докстринг
    обещает «хранилище в том объёме, в каком его знает конвейер», значило
    бы соврать в этом обещании. И практически: `Repository` реализует
    тестовый двойник целиком в `dict`, и он рос бы методами, которых
    никогда не вызовет.
    """

    def descriptions_before(self, cutoff: datetime) -> tuple[int, int]:
        """Сколько описаний старше границы и сколько в них байт."""
        ...

    def forget_descriptions(self, cutoff: datetime) -> int:
        """Обнулить их. Возвращает число тронутых строк."""
        ...

    def count_runs_before(self, cutoff: datetime) -> int:
        """Сколько закрытых строк журнала старше границы."""
        ...

    def forget_runs(self, cutoff: datetime) -> int:
        """Удалить их. Возвращает число удалённых строк."""
        ...

    def vacuum(self) -> None:
        """Ужать файл базы — иначе уборка не освобождает ни байта."""
        ...
