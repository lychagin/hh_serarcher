"""Отличие одиночного 403 от устойчивого — внутри одного прогона.

Спека §9 требует остановки на УСТОЙЧИВЫЙ 403, и планировщик это различие
знает: `scheduler.MAX_FORBIDDEN_IN_A_ROW` прямо написан про то, что
одиночный 403 бывает антиботом на конкретном запросе. В конвейере
различия не было вовсе — `PoliteClient` бросает `AccessForbidden` на
первом же 403, и он летел наружу мимо всех обработчиков. Один случайный
403 на одной странице из двадцати останавливал весь прогон, хотя
семнадцать страниц уже скачаны и сохранены; а два таких случайных 403 в
двух прогонах подряд останавливали и демон целиком.

Порог тот же, что у планировщика, и по той же причине. Считаются идущие
ПОДРЯД: успешный ответ между двумя 403 обнуляет счётчик — источник
отвечает, значит это не закрытая дверь.

Счётчик один на весь прогон и передаётся сквозь шаги: 403 на листинге и
403 на странице вакансии — это два подряд идущих отказа доступа, а не по
одному в двух независимых местах.
"""

import logging

from hh_search.errors import AccessForbidden
from hh_search.pipeline.stats import PARTIAL, RunStats

logger = logging.getLogger(__name__)

# Второй 403 ПОДРЯД — уже не случайность. Значение совпадает с
# `scheduler.MAX_FORBIDDEN_IN_A_ROW` не по совпадению: там то же
# рассуждение уровнем выше, о прогонах вместо запросов.
MAX_FORBIDDEN_IN_A_ROW = 2


class ForbiddenStreak:
    """Счётчик подряд идущих 403 за прогон."""

    def __init__(self, limit: int = MAX_FORBIDDEN_IN_A_ROW) -> None:
        self._limit = limit
        self.count = 0

    def survived(self) -> None:
        """Источник ответил — серия прервана."""
        self.count = 0

    def tolerate(self, error: AccessForbidden, what: str, stats: RunStats) -> None:
        """Пережить одиночный 403 или пробросить устойчивый.

        Проброс — это остановка прогона (спека §9): дальше конвейер к
        hh.ru не обращается. Пережитый 403 остаётся `partial` и громким
        `WARNING`: тихим он быть не может, потому что запрошенное так и
        не получено, а повторять запрос внутри прогона мы не будем.
        """
        self.count += 1
        if self.count >= self._limit:
            logger.error(
                "%d 403 подряд (%s): доступ закрыт устойчиво, прогон остановлен. "
                "Обходные пути не применяются",
                self.count,
                what,
            )
            raise error
        stats.degrade(PARTIAL, f"{what}: доступ закрыт ({error})")
        logger.warning(
            "%s: 403, но подряд он пока один — прогон продолжается. Второй подряд "
            "остановит его целиком (спека §9): %s",
            what,
            error,
        )
