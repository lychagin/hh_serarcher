"""Шаг 3 конвейера: единственный барьер перед дорогим шагом 4.

На этом шаге известен ТОЛЬКО заголовок. Discovery идёт по листингу
`/vacancies/{slug}`, который отдаёт id, url и название — компания, регион,
зарплата и дата публикации приходят со страницы вакансии, то есть уже
после того, как за неё заплачено запросом (спека §3.2, §4.1). Поэтому
отсева по региону здесь нет и быть не может.

Цена ошибки асимметрична, но необратимой она больше не является. Один и
тот же список `negative` обслуживает два механизма с несопоставимой
ценой ошибки: в скоринге совпадение стоит штраф, а вакансия остаётся в
отчёте; здесь оно означало `status='rejected'` НАВСЕГДА — ни следующий
прогон, ни правка конфига такую вакансию не доставали. Слова
образцового профиля писались как штрафные признаки и в отсеве убивали
целевые вакансии: «Backend-разработчик курьерской доставки» гибла от
слова «курьер». Решение владельца — снять саму необратимость: решение
отсева чисто локальное (заголовок уже в базе, сеть не нужна вовсе),
поэтому каждый прогон переоценивает отбракованные текущим конфигом и
возвращает в очередь те, что больше не совпадают (см.
`pipeline/discovery.py` и `SqliteRepository.requeue_prefiltered`).

Правило «отсеиваем только по явным стоп-словам, ничего не угадываем»
остаётся в силе: пропущенный мусор стоит одного запроса к hh.ru, а
ложный отказ теперь стоит задержки до ближайшей правки конфига.
"""

from hh_search.config.models import ProfileConfig
from hh_search.domain.models import DiscoveredVacancy
from hh_search.filtering.matching import SignalMatcher


class Prefilter:
    """Дешёвый отсев по заголовку — стоит до скачивания страницы вакансии."""

    def __init__(self, profile: ProfileConfig) -> None:
        # Пустой сигнал сюда не доедет: его отвергают и валидатор конфига
        # (`Signal` в config/models.py), и сам `_compile`. Проверять третий
        # раз здесь нечего — но тест на это в suite'е есть, потому что
        # именно в отсеве последствия такого сигнала необратимы.
        # Группы здесь разворачиваются в плоский список: на шаге 3 сигнал не
        # участвует ни в каком насыщении, а становится отдельной причиной
        # отказа в `reject_reason`, и склеивать причины не во что. Повторов
        # в этом списке быть не может — дубликаты отвергнуты конфигом.
        self._negative = SignalMatcher([signal for group in profile.negative for signal in group])

    def reason_to_reject(self, vacancy: DiscoveredVacancy) -> str | None:
        """Причина отказа или `None`, если вакансия идёт дальше."""
        return self.reason_for_title(vacancy.title)

    def reason_for_title(self, title: str) -> str | None:
        """То же решение, но по одному заголовку — всё, чем оно и живёт.

        Отдельный вход нужен переоценке уже отбракованных вакансий: у неё
        на руках только `id` и заголовок, читать ради решения ещё девять
        колонок незачем, а собирать из них `DiscoveredVacancy` — значит
        дать порче зарплаты или даты право повлиять на отказ, к которому
        они непричастны.

        В причину попадают ВСЕ совпавшие стоп-слова, а не первое: причина
        уходит в `reject_reason` и остаётся единственным следом решения,
        а «одно слово из трёх» превращает отладку списка сигналов в
        угадывание.
        """
        matched = self._negative.find(title)
        if matched:
            return f"стоп-слово в заголовке: {', '.join(matched)}"
        return None
