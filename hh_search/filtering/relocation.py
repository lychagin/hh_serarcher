"""Упоминание переезда СОТРУДНИКА в тексте вакансии.

Закрывает измеренную дыру: региональный штраф (§3 спеки
`2026-07-30-region-and-work-format-design.md`) считается по полю
`addressLocality` из разметки страницы, а требование переехать живёт в
ТЕКСТЕ описания. Вакансия с московским `area` и переездом в Елабугу в
теле описания проходит мимо штрафа целиком — живой случай 2026-08-26.

Отбор детерминированный и без сети, и это решение замера, а не вкуса:
llama3, спрошенная про переезд напрямую, нашла пять упоминаний из
одиннадцати — пропустив ровно деловые формулировки («релокационный
пакет, оплатим дорогу и первый месяц аренды»), то есть самые настоящие.
Слова находят все одиннадцать. Модели остаётся то, в чём она измеренно
сильна: назвать город и отличить требование от льготы (§0.7 спеки
`2026-08-26-local-llm-design.md`).
"""

import re

# Корни, а не формы: «релокация», «релокационный», «релоцируем» — одно
# слово, и перечислять его склонения значило бы повторять ошибку, из-за
# которой в скоринге пришлось перечислять написания `arm`/`arm64`.
_MENTION = re.compile(r"переезд|переех|релока|релоке|релоци|relocat", re.I)

# Тот же корень, но переезжают не люди. Два ложных срабатывания из
# одиннадцати на замере 2026-08-26 — «переезд приложений с legacy-
# инфраструктуры в Kubernetes» и «миграция систем с поэтапным переездом».
# Отсеиваются здесь, а НЕ моделью: та же llama3, спрошенная про класс
# «речь не о людях», не выбрала его ни разу из одиннадцати, включая обе
# эти вакансии.
_NOT_PEOPLE = re.compile(
    r"переезд\w*\s+(?:приложени|систем|данных|инфраструктур|сервис|проект|бд|баз)"
    r"|поэтапн\w*\s+переезд"
    r"|переезд\w*\s+(?:на|в|с)\s+(?:микросервис|kubernetes|k8s|облак|legacy|неё|нее|него)",
    re.I,
)


def mentions_relocation(text: str) -> bool:
    """Есть ли в тексте речь о переезде ЧЕЛОВЕКА.

    Технические упоминания вырезаются, и только потом ищется человеческое.
    Порядок значим: у одной живой вакансии переезжают и приложения, и сам
    сотрудник, и снять пометку из-за первого значило бы потерять второе.
    Цена ошибки асимметрична, как и везде в этом проекте: лишняя пометка
    стоит взгляда, пропущенная — переезда.
    """
    return bool(_MENTION.search(_NOT_PEOPLE.sub(" ", text)))
