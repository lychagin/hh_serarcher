class HhSearchError(Exception):
    """Базовая ошибка приложения."""


class AccessForbidden(HhSearchError):
    """Источник ответил 403. Прогон останавливается, обходить запрет нельзя."""


class StorageUnavailable(HhSearchError):
    """Каталог данных не читается или не пишется: права, том :ro, диск.

    Отдельный тип, а не голый `OSError`, потому что сообщение к нему
    приложено готовое: самая вероятная причина — несовпадение uid
    контейнера с владельцем тома, и об этом обязан узнать владелец, а не
    только traceback.
    """


class FetchFailed(HhSearchError):
    """Не удалось получить ресурс после всех повторов."""


class RobotsDisallowed(HhSearchError):
    """robots.txt запрещает обращение к этому пути."""


class DegenerateListing(FetchFailed):
    """Страница листинга без блока `ItemList`: измеренно ВРЕМЕННЫЙ отказ.

    hh.ru перемежающеся отдаёт код 200, целую вёрстку и страницу без
    блока, из которого берутся id вакансий; перекачка той же страницы
    проходит. Отдельный тип нужен ровно для того, чтобы отличать этот
    отказ от четырёх постоянных, которые тоже возбуждает `parse_listing`.

    Наследник `FetchFailed`, а не самостоятельный класс: все существующие
    обработчики продолжают работать без правок, и место, забывшее про
    новый тип, ведёт себя по-старому, а не падает.
    """


class LlmUnavailable(HhSearchError):
    """Локальная модель не дала пригодного ответа — по любой причине.

    Один тип на недоступность, таймаут, код ответа, мусор вместо JSON и
    ответ мимо схемы выбран сознательно: конвейер обязан поступать со
    всеми ими ОДИНАКОВО (§4 спеки
    `docs/superpowers/specs/2026-08-26-local-llm-design.md`) — посчитать
    вакансию по ключевым словам и идти дальше. Разные типы означали бы
    несколько веток обработки, не различающихся ничем, и первая же из них
    рано или поздно забыла бы про новый тип и уронила прогон.

    Не наследник `FetchFailed`: тот означает «источник вакансий недоступен,
    данные потеряны», и обработчики вокруг него считают потерю. Здесь
    ничего не потеряно — оценка по ключевым словам на месте.
    """
