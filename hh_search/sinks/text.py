"""Нормализация текста, который пришёл от работодателя.

Общая для markdown- и HTML-отчёта, и вынесена сюда именно поэтому: оба
кладут в «Топ» начало описания вакансии (спека §6 приёмника telegram
обещает, что структура двух отчётов совпадает), а копия набора управляющих
символов в двух модулях разошлась бы первой же правкой — то есть ровно тем
способом, от которого §6 и предостерегает.
"""

import re

from hh_search.domain.models import Salary, WorkFormat

# Описание с hh.ru — килобайты текста. Без обрезки «Топ» перестаёт быть
# выжимкой и читается дольше самой страницы вакансии.
SNIPPET_LENGTH = 200

# Подписи для отчёта, не для hh.ru: значения перечисления уходят в query
# запроса (см. `WorkFormat`), а здесь читатель, который штраф в скоринге
# видит как число и не понимает, за что он начислен.
_WORK_FORMAT_LABELS: dict[WorkFormat, str] = {
    WorkFormat.REMOTE: "удалённо",
    WorkFormat.HYBRID: "гибрид",
    WorkFormat.ON_SITE: "офис",
    WorkFormat.FIELD_WORK: "разъездной",
}

# Порог, с которого сумма печатается тысячами. Ниже него «900 $»
# превратилось бы в «0k $», то есть в неправду.
_THOUSAND = 1000

# Управляющие символы, которые не несут текста, но доезжают до файла:
# нулевой байт и прочие C0/C1 ломают grep и часть редакторов, а
# двунаправленные управляющие (U+202A..U+202E, U+2066..U+2069 и метки
# U+200E/U+200F) переворачивают показ остатка строки — и в редакторе, и в
# браузере. Заголовок пишет работодатель, а отчёт читают глазами.
# Пробельные из диапазона не перечислены: их убирает `collapse`.
_CONTROL = re.compile(
    r"[\x00-\x08\x0e-\x1f\x7f-\x9f\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u206f\ufeff]"
)


def collapse(text: str) -> str:
    """Одна строка вместо любого числа, без управляющих символов.

    Перевод строки внутри пункта списка ломает разметку markdown не хуже
    скобки; в HTML он не виден вовсе, зато мешает `grep` по файлу дня.
    """
    return " ".join(_CONTROL.sub("", text).split())


def snippet(text: str) -> str:
    """Начало описания: свёрнутое в строку и обрезанное до `SNIPPET_LENGTH`."""
    return collapse(text)[:SNIPPET_LENGTH]


def format_work_formats(formats: frozenset[WorkFormat]) -> str:
    """Формат работы человеку: без этого штраф в скоринге выглядит произволом.

    Пустое множество — «блока на странице не нашлось» ИЛИ «вакансия не
    обогащена» (`VacancyDetails.work_formats`), и в обоих случаях это не
    штраф, поэтому подпись обязана быть «формат не указан», а не «офис» —
    последнее утверждало бы то, чего мы не знаем.

    Несколько форматов — обычный случай (Team Lead Go из Москвы допускает
    ON_SITE, REMOTE и HYBRID сразу), и печатаются они через запятую в
    порядке `sorted()`: сам `frozenset` порядок не хранит, а хеш строк
    рандомизируется на процесс — без сортировки один и тот же набор
    печатался бы то так, то этак от запуска к запуску.
    """
    if not formats:
        return "формат не указан"
    return ", ".join(_WORK_FORMAT_LABELS[value] for value in sorted(formats))


def format_salary_short(salary: Salary) -> str | None:
    """Зарплата одной короткой строкой: «450–600k ₽», «от 487k ₽».

    Собирается из разобранных сумм, а не из `Salary.raw`: полная строка
    hh.ru («от 450 000 до 600 000 ₽ на руки») переносится на телефоне на
    вторую строку и рвёт мета-строку сообщения. Пометка «на руки» вместе с
    ней и теряется — она остаётся в файле дня и в CSV (решение владельца,
    §3 спеки вида сообщения).

    Тысячи ОТБРАСЫВАЮТСЯ, а не округляются: «от 487k» обещает меньше, чем
    написал работодатель, а «от 488k» обещало бы больше.

    `None` — ни одной суммы не разобрано. Тогда вызывающий код опускает
    часть строки целиком, а не пишет «зарплата не указана»: в сообщении из
    семи строк такая заглушка — семь строк шума.
    """
    low, high = salary.amount_from, salary.amount_to
    if low is None and high is None:
        return None
    thousands = all(value >= _THOUSAND for value in (low, high) if value is not None)
    suffix = "k" if thousands else ""
    currency = f" {salary.currency}" if salary.currency else ""

    def amount(value: int) -> str:
        # Неразрывный пробел здесь не нужен: строку никто не переносит по
        # словам, она уходит одним куском мета-строки.
        return str(value // _THOUSAND) if thousands else f"{value:_}".replace("_", " ")

    if low is not None and high is not None:
        return f"{amount(low)}–{amount(high)}{suffix}{currency}"
    if low is not None:
        return f"от {amount(low)}{suffix}{currency}"
    if high is not None:
        return f"до {amount(high)}{suffix}{currency}"
    return None
