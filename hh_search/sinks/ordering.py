"""Единственный порядок вакансий в отчёте — общий для всех приёмников.

До этого модуля сортировка была выписана в трёх местах отдельно
(`markdown_sink`, `html_report`, `telegram_message`) одним и тем же
выражением. Разъехавшись, они дали бы три отчёта об одном прогоне,
расходящиеся в том, что владелец увидит первым, — а именно первую строку
он и читает.
"""

from collections.abc import Sequence

from hh_search.domain.models import ScoredVacancy

# Значение семантики у вакансии, которую не эмбеддили. Ниже любого
# настоящего косинуса, но участвует ТОЛЬКО во второй позиции ключа,
# то есть внутри связки одинаковых ключевых оценок.
_UNKNOWN = -1.0


def by_relevance(vacancies: Sequence[ScoredVacancy]) -> list[ScoredVacancy]:
    """Ключевая оценка по убыванию, семантика — разрыватель связок.

    Порядок компонентов ключа и есть всё содержание §6 спеки
    `2026-08-26-local-llm-design.md`. Семантика стоит ВТОРОЙ, а не в
    сумме с оценкой: замер по всем 573 описаниям (§0.2.1) показал, что у
    246 из 539 отсеянных вакансий косинус выше, чем у худшей прошедшей
    порог, — весом он потянул бы наверх почти половину отсева. Вторым
    ключом он не может передвинуть вакансию мимо вакансии с иной оценкой
    ни при каком значении.

    `sorted` устойчива, и на это опирается инвариант деградации (§4):
    когда семантики нет ни у кого, все вторые ключи равны `_UNKNOWN`, и
    порядок остаётся ровно тем, в каком вакансии пришли из хранилища, —
    то есть выключенный Ollama не переставляет отчёт.
    """
    return sorted(
        vacancies,
        key=lambda item: (
            item.score.total,
            _UNKNOWN if item.semantic is None else item.semantic,
        ),
        reverse=True,
    )
